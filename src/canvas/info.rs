//! Implementation of features related to the format information and the version
//! information.

use super::Canvas;
use crate::{
    cast::As,
    types::{Color, EcLevel, NormalVersion, Version},
};

impl Canvas {
    /// Draws a big-endian integer onto the canvas with the given coordinates.
    ///
    /// The 1 bits will be plotted with `on_color` and the 0 bits with
    /// `off_color`. The coordinates will be extracted from the `coords`
    /// iterator. It will start from the most significant bits first, so
    /// _trailing_ zeros will be ignored.
    fn draw_number(
        &mut self,
        number: u32,
        bits: u32,
        on_color: Color,
        off_color: Color,
        coords: &[(i16, i16)],
    ) {
        let mut mask = 1 << (bits - 1);
        for &(x, y) in coords {
            let color = if (mask & number) == 0 {
                off_color
            } else {
                on_color
            };
            self.put(x, y, color);
            mask >>= 1;
        }
    }

    /// Draws the format info patterns for an encoded number.
    pub(super) fn draw_format_info_patterns_with_number(&mut self, format_info: u16) {
        let format_info = u32::from(format_info);
        match self.version {
            Version::Micro(_) => {
                self.draw_number(
                    format_info,
                    15,
                    Color::Dark,
                    Color::Light,
                    &FORMAT_INFO_COORDS_MICRO_QR,
                );
            }
            Version::Normal(_) => {
                self.draw_number(
                    format_info,
                    15,
                    Color::Dark,
                    Color::Light,
                    &FORMAT_INFO_COORDS_QR_MAIN,
                );
                self.draw_number(
                    format_info,
                    15,
                    Color::Dark,
                    Color::Light,
                    &FORMAT_INFO_COORDS_QR_SIDE,
                );
                // Dark module.
                self.put(8, -8, Color::Dark);
            }
            Version::RectMicro(_) => {}
        }
    }

    /// Reserves area to put in the format information.
    pub(super) fn draw_reserved_format_info_patterns(&mut self) {
        self.draw_format_info_patterns_with_number(0);
    }

    /// Draws the version information patterns.
    pub(super) fn draw_version_info_patterns(&mut self) {
        match self.version {
            Version::Micro(_) => {}
            Version::Normal(a) if a <= NormalVersion::V6 => {}
            Version::Normal(a) => {
                let version_info = VERSION_INFOS[(u8::from(a) - 7).as_usize()];
                self.draw_number(
                    version_info,
                    18,
                    Color::Dark,
                    Color::Light,
                    &VERSION_INFO_COORDS_BL,
                );
                self.draw_number(
                    version_info,
                    18,
                    Color::Dark,
                    Color::Light,
                    &VERSION_INFO_COORDS_TR,
                );
            }
            Version::RectMicro(a) => {
                let index = a.index();
                let ec_level = usize::from(self.ec_level != EcLevel::M);
                let version_info_left = RMQR_VERSION_INFOS_L[index][ec_level];
                let version_info_right = RMQR_VERSION_INFOS_R[index][ec_level];
                self.draw_number(
                    version_info_left,
                    18,
                    Color::Dark,
                    Color::Light,
                    &RMQR_VERSION_INFO_COORDS_L,
                );
                self.draw_number(
                    version_info_right,
                    18,
                    Color::Dark,
                    Color::Light,
                    &RMQR_VERSION_INFO_COORDS_R,
                );
            }
        }
    }
}

